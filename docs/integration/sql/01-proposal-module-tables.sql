-- =====================================================================================================
-- Proposal module - tables (PostgreSQL).  Run once on the existing application's database.
-- Creates only the proposal side. It does NOT create customer / software / service masters.
-- customer_id / software_id / service_id store the ids of the HOST application's master rows.
-- If the host ids are not BIGINT (UUID, varchar ...) change the three *_id column types AND the id type in the
-- Java entities (see docs/INTEGRATION-GUIDE.md, section 5).
-- Equivalent to the standalone Flyway migrations V1 (proposal part) + V3 of this project.
-- =====================================================================================================

-- global defaults for new proposals: rate card, loadings, document terms, reference numbering (single row, id = 1)
create table if not exists pricing_config (
    id                  bigint        primary key,
    tracking_room       numeric(12,2) not null,
    tracking_food       numeric(12,2) not null,
    tracking_salary     numeric(12,2) not null,
    data_audit_salary   numeric(12,2) not null,
    sr_exec_room        numeric(12,2) not null,
    sr_exec_food        numeric(12,2) not null,
    sr_exec_salary      numeric(12,2) not null,
    cost_per_branch     numeric(12,2) not null,
    travel_cost         numeric(12,2) not null,
    overhead_percent    numeric(6,2)  not null,
    profit_percent      numeric(6,2)  not null,
    gst_percent         numeric(5,2)  not null,
    validity_days       integer       not null,
    commencement_days   integer       not null,
    tracking_team_size  integer       not null,
    data_team_size      integer       not null,
    pay1                integer       not null,
    pay2                integer       not null,
    pay3                integer       not null,
    proposal_prefix     varchar(40)   not null default 'LTPL/PRO',
    po_prefix           varchar(40)   not null default 'LTPL/PO',
    include_financial_year boolean    not null default true,
    reset_each_year     boolean       not null default true,
    number_width        integer       not null default 5,
    series_start_no     integer       not null default 1
);

-- running counters of the reference / PO number series
create table if not exists doc_sequence (
    seq_key    varchar(60) primary key,
    last_value bigint not null
);

create table if not exists proposal (
    id                  bigint generated by default as identity primary key,
    seq_no              integer       not null,
    ref_no              varchar(60)   not null unique,
    version             integer       not null default 1,
    proposal_date       date          not null,
    status              varchar(20)   not null,
    customer_id         bigint        not null,          -- host customer id (optional FK, see end of file)
    contact_name        varchar(150),
    asset_count         integer       not null,
    branch_count        integer       not null,
    sr_exec_days        numeric(10,2) not null default 0,
    discount_percent    numeric(5,2)  not null default 0,
    notes               varchar(2000),

    -- rate card / terms are copied from pricing_config when the proposal is created
    tracking_room       numeric(12,2) not null,
    tracking_food       numeric(12,2) not null,
    tracking_salary     numeric(12,2) not null,
    data_audit_salary   numeric(12,2) not null,
    sr_exec_room        numeric(12,2) not null,
    sr_exec_food        numeric(12,2) not null,
    sr_exec_salary      numeric(12,2) not null,
    cost_per_branch     numeric(12,2) not null,
    travel_cost         numeric(12,2) not null,
    overhead_percent    numeric(6,2)  not null,
    profit_percent      numeric(6,2)  not null,
    gst_percent         numeric(5,2)  not null,
    validity_days       integer       not null,
    commencement_days   integer       not null,
    tracking_team_size  integer       not null,
    data_team_size      integer       not null,
    pay1                integer       not null,
    pay2                integer       not null,
    pay3                integer       not null,

    room_total          numeric(14,2) not null default 0,
    food_total          numeric(14,2) not null default 0,
    salary_total        numeric(14,2) not null default 0,
    branch_cost         numeric(14,2) not null default 0,
    sr_exec_cost        numeric(14,2) not null default 0,
    services_subtotal   numeric(14,2) not null default 0,
    overhead_amount     numeric(14,2) not null default 0,
    profit_amount       numeric(14,2) not null default 0,
    services_price      numeric(14,2) not null default 0,
    rate_per_asset      numeric(14,4) not null default 0,
    software_total      numeric(14,2) not null default 0,
    gross_total         numeric(14,2) not null default 0,
    discount_amount     numeric(14,2) not null default 0,
    net_total           numeric(14,2) not null default 0,
    gst_amount          numeric(14,2) not null default 0,
    grand_total         numeric(14,2) not null default 0,

    po_no               varchar(60),
    po_date             date,
    created_at          timestamp     not null,
    updated_at          timestamp     not null
);
create index if not exists idx_proposal_customer on proposal (customer_id);
create index if not exists idx_proposal_status on proposal (status);

create table if not exists proposal_software (
    id                    bigint generated by default as identity primary key,
    proposal_id           bigint        not null references proposal (id) on delete cascade,
    software_id           bigint        not null,         -- host software id
    assets_covered        integer       not null,
    price                 numeric(14,2) not null,
    implementation_charge numeric(14,2) not null default 0
);

create table if not exists proposal_service (
    id             bigint generated by default as identity primary key,
    proposal_id    bigint         not null references proposal (id) on delete cascade,
    service_id     bigint         not null,                -- host service id
    sequence_no    integer        not null default 0,
    in_scope       boolean        not null,
    assets_per_day numeric(12,2)  not null,
    effort_days    numeric(14,4)  not null default 0,
    room_cost      numeric(14,2)  not null default 0,
    food_cost      numeric(14,2)  not null default 0,
    salary_cost    numeric(14,2)  not null default 0,
    total_cost     numeric(14,2)  not null default 0,
    working_days   integer        not null default 0
);

